"""Register maps of the OpenISP modules, generated from one description per module.

For every description hdl/<module>/regs/<module>_regs.yml the tool writes

- hdl/<module>/src/<module>_regs_pkg.vhd  VHDL package: addresses, field positions, identification
- hdl/<module>/docs/register_map.md       documentation of every register and field
- sw/<module>_regs.h                      C header for the software

and checks the description against the register table of the module specification (section 7): every register
and field with its address, bits and access type, and every fixed reset value.

python tools/regmap.py          writes the generated files
python tools/regmap.py --check  fails when a generated file does not match its description or the description does
                                not match the specification (CI)
"""

import argparse
import difflib
import re
import sys
import textwrap
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

ACCESS = {
    "RO": "Read only",
    "RW": "Read and write",
    "W": "Write only, the argument of a command; reads as zero",
    "W1": "Write one: command; reads as zero",
    "W1C": "Sticky flag; write one to clear",
    "WO": "Write only; reads as zero",
}

HEADER_VHDL = [
    "-" * 99,
    "-- Copyright (c) 2026 by Julian Schneider",
    "-- Authors: Julian Schneider",
    "-" * 99,
]


class Field:
    def __init__(self, d):
        self.name = d["name"]
        self.access = d["access"]
        assert self.access in ACCESS, self.access
        self.reset = d.get("reset")
        self.description = d["description"]
        bits = str(d["bits"])
        if ":" in bits:
            hi, lo = bits.split(":")
            self.hi, self.lo = int(hi), int(lo)
        else:
            self.hi = self.lo = int(bits)
        self.bits = bits

    @property
    def single(self):
        return self.hi == self.lo

    @property
    def mask(self):
        return (1 << (self.hi - self.lo + 1)) - 1


class Register:
    def __init__(self, d, array=None):
        self.name = d["name"]
        self.offset = d["offset"]
        self.description = d["description"]
        self.fields = [Field(f) for f in d["fields"]]
        self.array = array
        self.address = (array["base"] if array else 0) + self.offset

    @property
    def reset(self):
        """Reset value of the register, None when a field has no fixed reset value."""
        value = 0
        for f in self.fields:
            if not isinstance(f.reset, int):
                return None
            value |= f.reset << f.lo
        return value


class Module:
    def __init__(self, source):
        self.source = source
        self.name = source.parent.parent.name
        d = yaml.safe_load(source.read_text(encoding="utf-8"))
        self.reg_id = d["id"]
        self.addr_bits = d["addr_bits"]
        self.title = d["title"]
        self.regs = [Register(r) for r in d["registers"]]
        self.arrays = [(a, [Register(r, a) for r in a["registers"]]) for a in d.get("arrays", [])]
        self.rel = source.relative_to(ROOT).as_posix()
        self.generated = f"Generated by tools/regmap.py from {self.rel}, do not edit."
        self.vhdl_path = ROOT / "hdl" / self.name / "src" / f"{self.name}_regs_pkg.vhd"
        self.doc_path = ROOT / "hdl" / self.name / "docs" / "register_map.md"
        self.header_path = ROOT / "sw" / f"{self.name}_regs.h"
        self.spec_path = ROOT / "hdl" / self.name / "docs" / "specification.md"

    @property
    def all_regs(self):
        return self.regs + [r for _, aregs in self.arrays for r in aregs]

    @property
    def prefix(self):
        return self.name.upper()


def camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))


def addr_text(reg):
    if reg.array:
        a = reg.array
        return f"0x{reg.address:03X} + {a['stride']} x {a['index']}"
    return f"0x{reg.address:02X}"


def reset_text(f):
    if f.reset is None:
        return ""
    if isinstance(f.reset, int):
        return f"0x{f.reset:X}" if f.reset > 9 else str(f.reset)
    return str(f.reset)


# -----------------------------------------------------------------------------------------------------
# VHDL package
# -----------------------------------------------------------------------------------------------------
def aligned(decls, indent="    "):
    """Constant declarations (name, type, value) with aligned colons and assignments."""
    wn = max(len(n) for n, _, _ in decls)
    wt = max(len(t) for _, t, _ in decls)
    return [f"{indent}constant {n:<{wn}} : {t:<{wt}} := {v};" for n, t, v in decls]


def section(title):
    return ["    " + "-" * 95, f"    -- {title}", "    " + "-" * 95]


def vhdl(m):
    lines = HEADER_VHDL + [
        "",
        "-" * 99,
        "-- Description",
        "-" * 99,
        f"-- Register map of {m.name}: addresses, field positions and identification of the AXI4-Lite registers.",
        f"-- {m.generated}",
        "--",
        f"-- Documentation: hdl/{m.name}/docs/register_map.md",
        "",
        "-" * 99,
        "-- Libraries",
        "-" * 99,
        "library ieee;",
        "    use ieee.std_logic_1164.all;",
        "",
        "-" * 99,
        "-- Package Header",
        "-" * 99,
        f"package {m.name}_regs_pkg is",
        "",
    ]
    lines += section("Identification and address width")
    lines += aligned([("RegMapId_c", "std_logic_vector(31 downto 0)", f'x"{m.reg_id:08X}"'),
                      ("RegAddrBits_c", "positive", str(m.addr_bits))])
    lines.append("")
    lines += section("Register addresses (byte addresses)")
    lines += aligned([(f"Reg{camel(r.name)}_c", "natural", f"16#{r.address:03X}#") for r in m.regs])
    for a, aregs in m.arrays:
        lines.append("")
        lines += section(f"{a['name']}: address of element {a['index']} = Reg<Name>_c + {a['index']} x "
                         f"Reg{camel(a['name'])}Stride_c")
        decls = [(f"Reg{camel(a['name'])}Stride_c", "natural", f"16#{a['stride']:03X}#")]
        decls += [(f"Reg{camel(r.name)}_c", "natural", f"16#{r.address:03X}#") for r in aregs]
        lines += aligned(decls)
    lines.append("")
    lines += section("Fields: bit of a one-bit field, lowest and highest bit of a wider field")
    for r in m.all_regs:
        decls = []
        for f in r.fields:
            base = f"{camel(r.name)}{camel(f.name)}"
            if f.single:
                decls.append((f"{base}_c", "natural", str(f.lo)))
            else:
                decls.append((f"{base}Lo_c", "natural", str(f.lo)))
                decls.append((f"{base}Hi_c", "natural", str(f.hi)))
        lines.append("")
        lines += aligned(decls)
    lines += ["", "end package;", ""]
    return "\n".join(lines)


# -----------------------------------------------------------------------------------------------------
# Documentation
# -----------------------------------------------------------------------------------------------------
def markdown(m):
    intro = (m.generated.replace("tools/regmap.py", "`tools/regmap.py`").replace(m.rel, f"`{m.rel}`") +
             f" The same description generates the VHDL package `{m.name}_regs_pkg` and the C header "
             f"`sw/{m.name}_regs.h`; `tools/regmap.py --check` compares it with the register table of the "
             "[specification](specification.md#7-register-map).")
    usage = (f"{m.title} Byte addresses of 32-bit registers on the AXI4-Lite slave ({m.addr_bits}-bit address); "
             "unused addresses and bits read as zero, and every access is answered with OKAY.")
    lines = [f"# {m.name}: Register Map", ""]
    lines += textwrap.wrap(intro, 120, break_on_hyphens=False, break_long_words=False)
    lines += [""] + textwrap.wrap(usage, 120, break_on_hyphens=False, break_long_words=False)
    lines += ["", "| Access | Meaning |", "| --- | --- |"]
    lines += [f"| {k} | {v} |" for k, v in ACCESS.items() if any(f.access == k for r in m.all_regs for f in r.fields)]
    lines += ["", "## Registers", "", "| Address | Register | Description |", "| --- | --- | --- |"]
    lines += [f"| {addr_text(r)} | [{r.name}](#{r.name.lower().replace('_', '_')}) | {r.description} |"
              for r in m.all_regs]
    for a, _ in m.arrays:
        lines += ["", f"{a['description']}"]
    lines += ["", "## Fields"]
    for r in m.all_regs:
        lines += ["", f"### {r.name}", "", f"Address {addr_text(r)}: {r.description}.", "",
                  "| Bits | Field | Access | Reset | Description |", "| --- | --- | --- | --- | --- |"]
        for f in sorted(r.fields, key=lambda f: -f.lo):
            lines.append(f"| {f.bits} | {f.name} | {f.access} | {reset_text(f)} | {f.description} |")
    lines.append("")
    return "\n".join(lines)


# -----------------------------------------------------------------------------------------------------
# C header
# -----------------------------------------------------------------------------------------------------
def defines(items):
    w = max(len(n) for n, _ in items)
    return [f"#define {n:<{w}} {v}" for n, v in items]


def header(m):
    p = m.prefix
    lines = [
        "/*",
        " * Copyright (c) 2026 by Julian Schneider",
        " * Authors: Julian Schneider",
        " *",
        f" * Register map of {m.name} (AXI4-Lite, byte addresses of 32-bit registers).",
        f" * {m.generated}",
        " */",
        "",
        f"#ifndef {p}_REGS_H",
        f"#define {p}_REGS_H",
        "",
        "/* Identification */",
    ]
    lines += defines([(f"{p}_ID", f"0x{m.reg_id:08X}u")])
    lines += ["", "/* Register addresses */"]
    lines += defines([(f"{p}_{r.name}", f"0x{r.address:03X}u") for r in m.regs])
    for a, aregs in m.arrays:
        i = a["index"]
        lines += ["", f"/* {a['description']} */"]
        items = [(f"{p}_{a['name']}_STRIDE", f"0x{a['stride']:03X}u")]
        items += [(f"{p}_{r.name}({i})", f"(0x{r.address:03X}u + ({i}) * 0x{a['stride']:03X}u)") for r in aregs]
        lines += defines(items)
    lines += ["", "/* Fields: position (SHIFT) and mask after the shift (MASK) */"]
    for r in m.all_regs:
        items = []
        for f in r.fields:
            items.append((f"{p}_{r.name}_{f.name}_SHIFT", f"{f.lo}u"))
            items.append((f"{p}_{r.name}_{f.name}_MASK", f"0x{f.mask:X}u"))
        lines += [""] + defines(items)
    lines += ["", f"#endif /* {p}_REGS_H */", ""]
    return "\n".join(lines)


# -----------------------------------------------------------------------------------------------------
# Comparison with the specification
# -----------------------------------------------------------------------------------------------------
def spec_rows(m):
    """Rows (address, register, bits, field, access, reset) of the register table of the specification."""
    text = m.spec_path.read_text(encoding="utf-8")
    sec = re.search(r"^## 7\. Register map\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    if not sec:
        return None
    rows = []
    addr = reg = None
    for line in sec.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 7 or not line.startswith("|") or cells[0] in ("Address", "---"):
            continue
        if cells[0]:
            addr, reg = cells[0], cells[1].strip("`").split("`")[0]
        access = cells[4].split()[0]
        reset = cells[5]
        rows.append((addr, reg, cells[2], cells[3].strip("`"), access, reset))
    return rows


def compare_spec(m):
    """Differences between the description and the specification."""
    rows = spec_rows(m)
    if rows is None:
        return [f"{m.spec_path.relative_to(ROOT).as_posix()}: no section '7. Register map'"]
    errors = []
    desc = []
    for r in m.all_regs:
        for f in sorted(r.fields, key=lambda f: f.lo):
            desc.append((r, f))
    spec = {}
    for addr, reg, bits, field, access, reset in rows:
        spec[(reg, field, bits)] = (addr, access, reset)
    seen = set()
    for r, f in desc:
        key = (r.name, f.name, f.bits)
        if key not in spec:
            errors.append(f"{m.name}: {r.name}.{f.name} ({f.bits}) is not in the specification")
            continue
        seen.add(key)
        addr, access, reset = spec[key]
        if not r.array and int(addr, 16) != r.address:
            errors.append(f"{m.name}: {r.name} at 0x{r.address:02X}, specification {addr}")
        if access != f.access:
            errors.append(f"{m.name}: {r.name}.{f.name} access {f.access}, specification {access}")
        if isinstance(f.reset, int) and re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", reset) and int(reset, 0) != f.reset:
            errors.append(f"{m.name}: {r.name}.{f.name} reset {f.reset:#x}, specification {reset}")
    for key in spec:
        if key not in seen:
            errors.append(f"{m.name}: {key[0]}.{key[1]} ({key[2]}) of the specification is not described")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is not up to date")
    args = parser.parse_args()
    modules = [Module(s) for s in sorted(ROOT.glob("hdl/*/regs/*_regs.yml"))]
    stale, errors = [], []
    for m in modules:
        errors += compare_spec(m)
        for path, text in ((m.vhdl_path, vhdl(m)), (m.doc_path, markdown(m)), (m.header_path, header(m))):
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(path)
                if args.check:
                    diff = difflib.unified_diff(current.splitlines(), text.splitlines(), str(path), "generated",
                                                lineterm="", n=1)
                    print("\n".join(list(diff)[:40]))
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8", newline="\n")
    for e in dict.fromkeys(errors):
        print(e)
    rel = [p.relative_to(ROOT).as_posix() for p in stale]
    if args.check:
        if stale:
            print("Not up to date (run python tools/regmap.py):", ", ".join(rel))
        if stale or errors:
            return 1
        print(f"Register maps of {len(modules)} modules up to date and in line with their specifications")
        return 0
    print("Written:", ", ".join(rel) if rel else "nothing (up to date)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
